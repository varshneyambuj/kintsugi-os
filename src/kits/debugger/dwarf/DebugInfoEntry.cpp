/**
 * @brief Stores DW_AT_decl_file into the DIE's declaration location.
 *
 * @retval B_OK                  Stored successfully.
 * @retval ATTRIBUTE_NOT_HANDLED This DIE has no declaration-location storage.
 */
status_t
DebugInfoEntry::AddAttribute_decl_file(uint16 attributeName,
	const AttributeValue& value)
{
	if (DeclarationLocation* location = GetDeclarationLocation()) {
		location->SetFile(value.constant);
		return B_OK;
	}

	return ATTRIBUTE_NOT_HANDLED;
}


