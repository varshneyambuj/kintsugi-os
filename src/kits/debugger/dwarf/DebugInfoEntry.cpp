/**
 * @brief Reads DW_AT_decl_file via the DIE's declaration-location storage.
 *
 * @param _file Output file index (1-based; resolves against CU file table).
 * @return @c true on success, @c false when no decl-file is available.
 */
bool
DebugInfoEntry::GetDeclarationFile(uint32& _file) const
{
	DeclarationLocation* location = const_cast<DebugInfoEntry*>(this)
		->GetDeclarationLocation();
	if (location == NULL || !location->IsFileSet())
		return false;

	_file = location->file;
	return true;
}


