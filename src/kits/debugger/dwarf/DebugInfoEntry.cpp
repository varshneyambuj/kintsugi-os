/**
 * @brief Stores DW_AT_location into the DIE's location description.
 *
 * Recognises both inline expression blocks and location-list pointers.
 *
 * @retval B_OK                  Stored successfully.
 * @retval B_BAD_DATA            Attribute class was incompatible.
 * @retval ATTRIBUTE_NOT_HANDLED This DIE has no location-description storage.
 */
status_t
DebugInfoEntry::AddAttribute_location(uint16 attributeName,
	const AttributeValue& value)
{
	if (LocationDescription* location = GetLocationDescription()) {
		if (value.attributeClass == ATTRIBUTE_CLASS_LOCLIST) {
			location->SetToLocationList(value.pointer);
			return B_OK;
		}

		if (value.attributeClass == ATTRIBUTE_CLASS_BLOCK) {
			location->SetToExpression(value.block.data, value.block.length);
			return B_OK;
		}
		return B_BAD_DATA;
	}

	return ATTRIBUTE_NOT_HANDLED;
}


