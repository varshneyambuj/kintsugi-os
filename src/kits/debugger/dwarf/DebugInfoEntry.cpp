/**
 * @brief Stores a parsed AttributeValue into a DynamicAttributeValue field.
 *
 * Maps each supported attribute class (constant, reference, block) onto
 * the matching DynamicAttributeValue setter.
 *
 * @param toSet  Output field to populate.
 * @param value  Parsed attribute value.
 * @retval B_OK        Stored successfully.
 * @retval B_BAD_DATA  Attribute class was not one of the supported three.
 */
status_t
DebugInfoEntry::SetDynamicAttributeValue(DynamicAttributeValue& toSet,
	const AttributeValue& value)
{
	switch (value.attributeClass) {
		case ATTRIBUTE_CLASS_CONSTANT:
			toSet.SetTo(value.constant);
			return B_OK;
		case ATTRIBUTE_CLASS_REFERENCE:
			toSet.SetTo(value.reference);
			return B_OK;
		case ATTRIBUTE_CLASS_BLOCK:
			toSet.SetTo(value.block.data, value.block.length);
			return B_OK;
		default:
			return B_BAD_DATA;
	}
}


/**
 * @brief Stores a parsed AttributeValue into a ConstantAttributeValue field.
 *
 * Mirrors @ref SetDynamicAttributeValue but accepts strings instead of
 * DIE references.
 *
 * @param toSet  Output field to populate.
 * @param value  Parsed attribute value.
 * @retval B_OK        Stored successfully.
 * @retval B_BAD_DATA  Attribute class was not constant/string/block.
 */
status_t
DebugInfoEntry::SetConstantAttributeValue(ConstantAttributeValue& toSet,
	const AttributeValue& value)
{
	switch (value.attributeClass) {
		case ATTRIBUTE_CLASS_CONSTANT:
			toSet.SetTo(value.constant);
			return B_OK;
		case ATTRIBUTE_CLASS_STRING:
			toSet.SetTo(value.string);
			return B_OK;
		case ATTRIBUTE_CLASS_BLOCK:
			toSet.SetTo(value.block.data, value.block.length);
			return B_OK;
		default:
			return B_BAD_DATA;
	}
}


/**
 * @brief Stores a parsed AttributeValue into a MemberLocation field.
 *
 * Constants become byte offsets, blocks become DWARF expressions, and
 * pointer values become location-list references.
 *
 * @param toSet  Output field to populate.
 * @param value  Parsed attribute value.
 * @retval B_OK        Stored successfully.
 * @retval B_BAD_DATA  Attribute class was not constant/block/loclist.
 */
status_t
DebugInfoEntry::SetMemberLocation(MemberLocation& toSet,
	const AttributeValue& value)
{
	switch (value.attributeClass) {
		case ATTRIBUTE_CLASS_CONSTANT:
			toSet.SetToConstant(value.constant);
			return B_OK;
		case ATTRIBUTE_CLASS_BLOCK:
			toSet.SetToExpression(value.block.data, value.block.length);
			return B_OK;
		case ATTRIBUTE_CLASS_LOCLIST:
			toSet.SetToLocationList(value.pointer);
			return B_OK;
		default:
			return B_BAD_DATA;
	}
}
