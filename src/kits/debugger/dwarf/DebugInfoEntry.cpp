/**
 * @file DebugInfoEntry.cpp
 * @brief Implementation of the DebugInfoEntry abstract base.
 *
 * Provides default no-op or NULL-returning implementations for every
 * polymorphic accessor and every @c AddAttribute_xxx setter, so that
 * concrete DIE subclasses (defined in DebugInfoEntries.cpp) only need
 * to override the setters relevant to their DWARF tag.  The bulk of
 * the file is generated by the @c DEFINE_DEBUG_INFO_ENTRY_ATTR_SETTER
 * macro which expands to a default "not handled" stub.
 */

#include "DebugInfoEntries.h"

#include <new>

#include "AttributeValue.h"
